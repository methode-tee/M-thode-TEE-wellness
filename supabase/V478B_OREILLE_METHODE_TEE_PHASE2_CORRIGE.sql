-- ---------------------------------------------------------------------------
-- 2. LE DICTIONNAIRE APPREND AUTOMATIQUEMENT LES NOUVEAUX ALIAS TEXTE
-- ---------------------------------------------------------------------------
-- Important : on AJOUTE les alias à speech_aliases sans jamais supprimer les
-- variantes vocales saisies manuellement.
create or replace function public.food_dictionary_sync_speech_aliases()
returns trigger
language plpgsql
set search_path=public
as $$
begin
  select coalesce(array_agg(distinct v order by v),'{}'::text[])
  into new.speech_aliases
  from unnest(
    coalesce(new.speech_aliases,'{}'::text[])
    || coalesce(new.aliases,'{}'::text[])
    || array[new.canonical_name]
  ) as x(v)
  where nullif(trim(v),'') is not null;
  return new;
end;
$$;

drop trigger if exists food_dictionary_sync_speech_aliases_trigger on public.food_dictionary;
create trigger food_dictionary_sync_speech_aliases_trigger
before insert or update of canonical_name,aliases on public.food_dictionary
for each row execute function public.food_dictionary_sync_speech_aliases();

-- Backfill non destructif : conserve les alias V477 + ajoute les éventuels alias
-- catalogue apparus depuis.
with merged_aliases as (
  select
    d.id,
    coalesce(array_agg(distinct a.v order by a.v),'{}'::text[]) as merged
  from public.food_dictionary d
  cross join lateral unnest(
    coalesce(d.speech_aliases,'{}'::text[])
    || coalesce(d.aliases,'{}'::text[])
    || array[d.canonical_name]
  ) as a(v)
  where nullif(trim(a.v),'') is not null
  group by d.id
)
update public.food_dictionary d
set speech_aliases = m.merged
from merged_aliases m
where d.id = m.id
  and d.speech_aliases is distinct from m.merged;

