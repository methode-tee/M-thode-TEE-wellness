-- ---------------------------------------------------------------------------
-- 4. NETTOYAGE LÉGER D'UNE PHRASE DICTÉE
-- ---------------------------------------------------------------------------
-- On ne « comprend » pas la phrase avec un LLM. On retire seulement les mots de
-- conversation/quantité les plus fréquents afin d'obtenir un fallback CIQUAL utile.
-- La résolution des plats culturels continue, elle, à scanner la phrase complète.
create or replace function public.food_speech_focus(value text)
returns text
language sql
immutable
parallel safe
as $$
  with tokens as (
    select w,ord
    from regexp_split_to_table(public.food_normalize(value),'[[:space:]]+')
         with ordinality as t(w,ord)
    where nullif(w,'') is not null
      and w not in (
        'j','je','jai','ai','mange','manges','mangee','manger','pris','prends','prendre',
        'viens','venir','vais','veux','voudrais','eu','avais','avait','pour',
        'du','de','la','le','les','des','un','une','d','l','au','aux',
        'avec','et','puis','ce','cette','ces','mon','ma','mes',
        'matin','midi','soir','aujourdhui','aujourd','hui',
        'deux','trois','quatre','cinq','six','sept','huit','neuf','dix',
        'demi','demie','moitie','peu','environ',
        'gramme','grammes','g','ml','cl','litre','litres',
        'bol','portion','portions','tranche','tranches','cuillere','cuilleres'
      )
  )
  select coalesce(string_agg(w,' ' order by ord),'') from tokens;
$$;

grant execute on function public.food_speech_focus(text) to authenticated;

-- ---------------------------------------------------------------------------
-- 5. RÉSOLVEUR UNIVERSEL V2 : DICTIONNAIRE CULTUREL + CIQUAL
-- ---------------------------------------------------------------------------
-- AUCUNE fonction existante n'est remplacée. Le futur bouton « Le dire à Tee »
-- appellera resolve_food_speech_v2 uniquement lorsqu'on le branchera dans l'app.
--
-- Déduplication : lorsqu'un plat historique et une ligne CIQUAL partagent le même
-- ciqual_code (ex. les deux entrées Achu), ils deviennent UN SEUL candidat vocal.
create or replace function public.resolve_food_speech_v2(
  p_text text,
  p_limit integer default 8
)
returns table(
  food_ref text,
  source_kind text,
  dictionary_id uuid,
  multimodal_key text,
  ciqual_code text,
  canonical_name text,
  display_name text,
  country text,
  culture text,
  matched_term text,
  match_type text,
  confidence text,
  requires_confirmation boolean,
  match_rank integer
)
language sql
stable
security invoker
set search_path=public
as $$
  with q as (
    select
      public.food_normalize(left(coalesce(p_text,''),1000)) as v,
      public.food_speech_focus(left(coalesce(p_text,''),1000)) as focus
  ),
  dict_terms as (
    select d.id,d.multimodal_key,d.ciqual_code,d.canonical_name,d.display_name,d.country,d.culture,d.priority,
           d.normalized_name term_norm,d.canonical_name term_raw,'canonical'::text term_kind,0::integer kind_penalty
    from public.food_dictionary d
    where d.enabled and d.speech_enabled

    union all

    select d.id,d.multimodal_key,d.ciqual_code,d.canonical_name,d.display_name,d.country,d.culture,d.priority,
           public.food_normalize(a),a,'alias'::text,2::integer
    from public.food_dictionary d
    cross join lateral unnest(d.aliases) a
    where d.enabled and d.speech_enabled and length(public.food_normalize(a))>=2

    union all

    select d.id,d.multimodal_key,d.ciqual_code,d.canonical_name,d.display_name,d.country,d.culture,d.priority,
           public.food_normalize(a),a,'speech_alias'::text,1::integer
    from public.food_dictionary d
    cross join lateral unnest(d.speech_aliases) a
    where d.enabled and d.speech_enabled and length(public.food_normalize(a))>=2

    union all

    select d.id,d.multimodal_key,d.ciqual_code,d.canonical_name,d.display_name,d.country,d.culture,d.priority,
           o.alias_normalized,o.alias,'speech_override'::text,0::integer
    from public.food_speech_alias_overrides o
    join public.food_dictionary d on d.id=o.dictionary_id
    where o.enabled and o.locale='fr-FR' and d.enabled and d.speech_enabled
  ),
  dict_hits_raw as (
    select
      case when t.ciqual_code is not null then 'ciqual:'||t.ciqual_code else 'dict:'||coalesce(t.multimodal_key,t.id::text) end entity_key,
      'dictionary'::text source_kind,
      t.id dictionary_id,t.multimodal_key,t.ciqual_code,t.canonical_name,t.display_name,t.country,t.culture,
      t.term_raw matched_term,t.term_kind match_type,
      (
        case
          when q.v=t.term_norm then 0
          when q.focus<>'' and q.focus=t.term_norm then 1
          when position(' '||t.term_norm||' ' in ' '||q.v||' ')>0 then 8
          when q.focus<>'' and position(' '||t.term_norm||' ' in ' '||q.focus||' ')>0 then 9
          else 999
        end
        + t.kind_penalty
        + greatest(0,least(10,t.priority/20))
      )::integer rank_value
    from dict_terms t cross join q
    where length(t.term_norm)>=2
      and length(q.v)>=2
      and (
        q.v=t.term_norm
        or (q.focus<>'' and q.focus=t.term_norm)
        or position(' '||t.term_norm||' ' in ' '||q.v||' ')>0
        or (q.focus<>'' and position(' '||t.term_norm||' ' in ' '||q.focus||' ')>0)
      )
  ),
  component_hints as (
    select
      case when d.ciqual_code is not null then 'ciqual:'||d.ciqual_code else 'dict:'||coalesce(d.multimodal_key,d.id::text) end entity_key,
      'dictionary'::text source_kind,
      d.id dictionary_id,d.multimodal_key,d.ciqual_code,d.canonical_name,d.display_name,d.country,d.culture,
      comp.value matched_term,'component_hint'::text match_type,
      (75 + greatest(0,least(10,d.priority/20)))::integer rank_value
    from public.food_dictionary d
    cross join q
    cross join lateral jsonb_array_elements_text(
      case when jsonb_typeof(d.typical_components)='array' then d.typical_components else '[]'::jsonb end
    ) as comp(value)
    where d.enabled and d.speech_enabled
      and length(q.focus)>=3
      and public.food_normalize(comp.value)=q.focus
  ),
  ciqual_hits as (
    select
      'ciqual:'||c.code entity_key,
      'ciqual'::text source_kind,
      null::uuid dictionary_id,null::text multimodal_key,c.code ciqual_code,
      c.name canonical_name,c.name display_name,null::text country,null::text culture,
      c.name matched_term,'ciqual'::text match_type,
      (
        case
          when public.food_normalize(c.name)=q.focus then 3
          when q.focus<>'' and public.food_normalize(c.name) like q.focus||' %' then 10
          when q.focus<>'' and position(' '||q.focus||' ' in ' '||public.food_normalize(c.name)||' ')>0 then 22
          when q.focus<>'' and position(' '||q.focus||' ' in ' '||public.food_normalize(c.search_text)||' ')>0 then 34
          else 999
        end
        + case when coalesce(c.source,'CIQUAL')='CIQUAL' then 0 else 2 end
      )::integer rank_value
    from public.ciqual_foods c cross join q
    where length(q.focus)>=3
      and (
        public.food_normalize(c.name)=q.focus
        or public.food_normalize(c.name) like q.focus||' %'
        or position(' '||q.focus||' ' in ' '||public.food_normalize(c.name)||' ')>0
        or position(' '||q.focus||' ' in ' '||public.food_normalize(c.search_text)||' ')>0
      )
  ),
  ciqual_override_hits as (
    select
      'ciqual:'||c.code entity_key,
      'ciqual'::text source_kind,
      null::uuid dictionary_id,null::text multimodal_key,c.code ciqual_code,
      c.name canonical_name,c.name display_name,null::text country,null::text culture,
      o.alias matched_term,'speech_override'::text match_type,
      (
        case
          when q.v=o.alias_normalized then 0
          when q.focus<>'' and q.focus=o.alias_normalized then 1
          when position(' '||o.alias_normalized||' ' in ' '||q.v||' ')>0 then 8
          else 999
        end
        + greatest(0,least(10,o.priority/20))
      )::integer rank_value
    from public.food_speech_alias_overrides o
    join public.ciqual_foods c on c.code=o.ciqual_code
    cross join q
    where o.enabled and o.locale='fr-FR'
      and (
        q.v=o.alias_normalized
        or (q.focus<>'' and q.focus=o.alias_normalized)
        or position(' '||o.alias_normalized||' ' in ' '||q.v||' ')>0
      )
  ),
  all_hits as (
    select * from dict_hits_raw where rank_value<999
    union all
    select * from component_hints
    union all
    select * from ciqual_hits where rank_value<999
    union all
    select * from ciqual_override_hits where rank_value<999
  ),
  entity_dedup as (
    select distinct on (entity_key)
      entity_key,source_kind,dictionary_id,multimodal_key,ciqual_code,canonical_name,display_name,country,culture,
      matched_term,match_type,rank_value
    from all_hits
    order by entity_key,rank_value,(source_kind='dictionary') desc,length(coalesce(matched_term,'')) desc,canonical_name
  )
  select
    entity_key as food_ref,
    source_kind,dictionary_id,multimodal_key,ciqual_code,canonical_name,display_name,country,culture,
    matched_term,match_type,
    case
      when rank_value<=5 then 'exact'
      when rank_value<=20 then 'strong'
      when rank_value<=45 then 'probable'
      else 'possible'
    end as confidence,
    true as requires_confirmation,
    rank_value as match_rank
  from entity_dedup
  order by rank_value,
           case when source_kind='dictionary' then 0 else 1 end,
           length(coalesce(matched_term,'')) desc,
           display_name
  limit greatest(1,least(coalesce(p_limit,8),12));
$$;

grant execute on function public.resolve_food_speech_v2(text,integer) to authenticated;

commit;

