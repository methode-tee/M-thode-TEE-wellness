-- ---------------------------------------------------------------------------
-- 1. VOCABULAIRE VOCAL MANUEL / PHONÉTIQUE
-- ---------------------------------------------------------------------------
-- Les alias historiques restent dans food_dictionary.aliases / speech_aliases.
-- Cette table sert uniquement aux variantes typiques de dictée vocale et peut être
-- enrichie plus tard sans modifier le moteur alimentaire historique.
create table if not exists public.food_speech_alias_overrides (
  id bigint generated by default as identity primary key,
  alias text not null,
  alias_normalized text generated always as (public.food_normalize(alias)) stored,
  locale text not null default 'fr-FR',
  dictionary_id uuid references public.food_dictionary(id) on delete cascade,
  ciqual_code text references public.ciqual_foods(code) on delete cascade,
  priority integer not null default 10,
  enabled boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint food_speech_alias_overrides_target_check
    check (num_nonnulls(dictionary_id,ciqual_code)=1),
  constraint food_speech_alias_overrides_alias_check
    check (length(alias_normalized)>=2),
  constraint food_speech_alias_overrides_priority_check
    check (priority between 0 and 1000)
);

create unique index if not exists food_speech_alias_dict_uidx
  on public.food_speech_alias_overrides(alias_normalized,locale,dictionary_id)
  where dictionary_id is not null;

create unique index if not exists food_speech_alias_ciqual_uidx
  on public.food_speech_alias_overrides(alias_normalized,locale,ciqual_code)
  where ciqual_code is not null;

create index if not exists food_speech_alias_lookup_idx
  on public.food_speech_alias_overrides(enabled,locale,alias_normalized,priority);

alter table public.food_speech_alias_overrides enable row level security;
