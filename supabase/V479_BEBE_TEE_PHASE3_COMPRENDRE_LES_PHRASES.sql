create or replace function public.resolve_food_speech_phrase_v3_json(
  p_text text,
  p_limit_items integer default 12
)
returns jsonb
language sql
stable
security invoker
set search_path=public
as $$
  with items as (
    select * from public.resolve_food_speech_phrase_v3(p_text,p_limit_items)
  )
  select jsonb_build_object(
    'input',coalesce(p_text,''),
    'item_count',count(*),
    'all_foods_resolved',coalesce(bool_and(food_ref is not null),false),
    'requires_confirmation',true,
    'items',coalesce(jsonb_agg(to_jsonb(items) order by item_index),'[]'::jsonb)
  )
  from items;
$$;

