create or replace function public.mt_admin_food_guidance_search_v1(
  p_query text default '',
  p_limit integer default 80
) returns jsonb
language plpgsql security definer set search_path=public
as $$
declare v_q text:=public.food_normalize(coalesce(p_query,'')); v_limit int:=greatest(1,least(coalesce(p_limit,80),200)); v_result jsonb;
begin
  if not public.is_admin() then raise exception 'admin required'; end if;
  with src as (
    select p.profile_key,
      case when p.dictionary_id is not null then 'dictionary' else 'ciqual' end source_kind,
      p.dictionary_id,p.ciqual_code::text ciqual_code,p.display_name,
      g.guidance_portion_g,g.portion_source,g.guidance_role,g.auto_suggest_mode,g.quality_rank,g.ready_to_eat,g.preparation_state,g.contexts,g.nutrient_scores,g.priority_nutrients,g.flags,g.manual_override,g.admin_note,g.curated_version,g.updated_at,
      (g.profile_key is not null) curated
    from public.mt_food_culinary_profiles_v1 p
    left join public.mt_food_guidance_profiles_v1 g on g.profile_key=p.profile_key
    where v_q='' or public.food_normalize(p.display_name) like '%'||v_q||'%' or public.food_normalize(p.profile_key) like '%'||v_q||'%'
    order by (g.profile_key is not null) desc, lower(p.display_name),p.profile_key
    limit v_limit
  )
  select coalesce(jsonb_agg(to_jsonb(src)),'[]'::jsonb) into v_result from src;
  return v_result;
end;$$;
