-- V2 : wrapper additif au-dessus de V1. Il enrichit les candidats sans remplacer V1.
create or replace function public.mt_food_guidance_v2(
  p_focus text default 'protein',
  p_target_date date default current_date,
  p_meal_context text default null,
  p_limit integer default 12
) returns jsonb
language plpgsql security definer set search_path=public
as $$
declare
  uid uuid:=auth.uid();
  base jsonb;
  enriched jsonb:='[]'::jsonb;
  memory_strong boolean:=false;
begin
  if uid is null then raise exception 'auth required'; end if;
  base:=public.mt_food_guidance_v1(p_focus,p_target_date,p_meal_context,p_limit);
  memory_strong:=coalesce((base->'memory'->>'strong')::boolean,false);

  with elems as (
    select e.value c,e.ordinality ord
    from jsonb_array_elements(coalesce(base->'candidates','[]'::jsonb)) with ordinality e(value,ordinality)
  ), enriched_rows as (
    select e.ord,
      e.c || jsonb_strip_nulls(jsonb_build_object(
        'preparation_state',case when e.c->>'source_kind'='scanned' then 'ready' else coalesce(g.preparation_state,'ready') end,
        'familiarity_level',case
          when coalesce((e.c->>'use_count_60d')::int,0)>=2 then 'habit'
          when coalesce((e.c->>'use_count_60d')::int,0)=1 then 'consumed'
          when coalesce(ev.chosen_count,0)>=1 then 'tee_chosen'
          when memory_strong and coalesce((e.c->>'memory_affinity_score')::numeric,0)>=10 and coalesce((e.c->>'culture_familiar')::boolean,false) then 'similar'
          else null end,
        'habit_evidence_count',coalesce((e.c->>'use_count_60d')::int,0),
        'tee_chosen_count',coalesce(ev.chosen_count,0),
        'similarity_proven',memory_strong and coalesce((e.c->>'memory_affinity_score')::numeric,0)>=10 and coalesce((e.c->>'culture_familiar')::boolean,false)
      )) c
    from elems e
    left join public.mt_food_guidance_profiles_v1 g on g.profile_key=nullif(e.c->>'curated_profile_key','')
    left join lateral (
      select count(*) filter(where event_type='chosen')::int chosen_count
      from public.user_food_guidance_events x
      where x.user_id=uid and x.candidate_ref=e.c->>'candidate_ref' and x.event_date>=coalesce(p_target_date,current_date)-59
    ) ev on true
  )
  select coalesce(jsonb_agg(c order by ord),'[]'::jsonb) into enriched from enriched_rows;

  base:=jsonb_set(base,'{candidates}',enriched,true);
  base:=jsonb_set(base,'{version}',to_jsonb('V4896603R1_PRACTICAL_CONTEXT_GUIDANCE'::text),true);
  base:=jsonb_set(base,'{rules}',coalesce(base->'rules','{}'::jsonb) || jsonb_build_object(
    'preparation_state',true,
    'closing_excludes_requires_cooking',true,
    'morning_can_prepare_ahead',true,
    'meal_contexts_reviewed_3794',true,
    'habit_badges_require_exact_use',true,
    'similar_badge_requires_strong_memory',true,
    'voice_unchanged',true,'adapter_unchanged',true,'food_day_unchanged',true
  ),true);
  return base;
end;$$;
